#[test]
fn attribution_is_opt_in_and_lands_in_the_output() {
    let components = [button()];
    let config = GeneratorConfig::with_attribution("Generated by Example");

    // Every target that can carry a comment must write the attribution into its
    // output. JsonGenerator is absent on purpose: JSON has no comment syntax, so
    // it documents that it ignores the config rather than corrupting the payload.
    let generators: Vec<(&str, Box<dyn CodeGenerator>)> = vec![
        ("leptos", Box::new(LeptosGenerator::new(Default::default()))),
        ("html", Box::new(HtmlGenerator)),
        ("markdown", Box::new(MarkdownGenerator)),
        ("json_schema", Box::new(JsonSchemaGenerator)),
        ("typescript", Box::new(TypeScriptGenerator)),
        ("react", Box::new(ReactGenerator)),
        ("vue", Box::new(VueGenerator)),
        ("css", Box::new(CssGenerator)),
        ("tailwind", Box::new(TailwindHtmlGenerator)),
        ("svelte", Box::new(SvelteGenerator)),
    ];

    for (name, generator) in generators {
        let output = generator.generate_with(&config, &components, &[]).unwrap();
        assert!(
            output.contains("Generated by Example"),
            "the configured attribution must appear in the {name} output, got:\n{output}"
        );
    }
}

#[test]
fn json_schema_keeps_the_attribution_valid() {
    let components = [button()];
    let config = GeneratorConfig::with_attribution("Generated by Example");
    let output = JsonSchemaGenerator
        .generate_with(&config, &components, &[])
        .unwrap();

    // The note goes in `$comment`, the keyword draft-07 reserves for this, so the
    // document stays parseable and still passes validation.
    let parsed: serde_json::Value =
        serde_json::from_str(&output).expect("output must be valid JSON");
    assert_eq!(
        parsed.get("$comment").and_then(|v| v.as_str()),
        Some("Generated by Example")
    );
    assert!(
        parsed.get("$schema").is_some(),
        "the $comment must not displace the rest of the schema"
    );

    // Parseable is not the same as valid: compile the document as a real draft-07
    // schema, or a structural regression would sail through the checks above.
    let validator = jsonschema::draft7::new(&parsed)
        .expect("the generated document must compile as a draft-07 schema");

    // A layout the schema describes must validate, and one it forbids must not, so
    // the test also proves the schema still constrains anything.
    let good = serde_json::to_value(&components).unwrap();
    assert!(
        validator.is_valid(&good),
        "a component array the schema describes must validate, errors: {:?}",
        validator.iter_errors(&good).collect::<Vec<_>>()
    );

    let bad = serde_json::json!([{ "NotAComponent": {} }]);
    assert!(
        !validator.is_valid(&bad),
        "the schema must reject an unknown component type"
    );
}

#[test]
fn json_payload_is_never_polluted_by_an_attribution() {
    let components = [button()];
    let config = GeneratorConfig::with_attribution("Generated by Example");
    let output = JsonGenerator
        .generate_with(&config, &components, &[])
        .unwrap();

    // The payload is the caller's own data, so the generator must not invent a
    // field for the note. It ignores the attribution instead of corrupting output.
    let parsed: serde_json::Value =
        serde_json::from_str(&output).expect("output must be valid JSON");
    assert_eq!(parsed, serde_json::to_value(&components).unwrap());
    assert!(
        !output.contains("Generated by Example"),
        "the JSON payload must not gain an attribution field, got:\n{output}"
    );
}

