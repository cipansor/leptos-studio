//! The crate's public contract: every target is reachable through one trait, and
//! nothing names a product unless the caller asks for it.

use canvas_codegen::domain::{ButtonComponent, CanvasComponent};
use canvas_codegen::generators::{
    CssGenerator, HtmlCodeGenerator, HtmlGenerator, JsonCodeGenerator, JsonGenerator,
    JsonSchemaGenerator, LeptosCodeGenerator, LeptosGenerator, MarkdownCodeGenerator,
    MarkdownGenerator, ReactGenerator, SvelteGenerator, TailwindHtmlGenerator, TypeScriptGenerator,
    VueGenerator,
};
use canvas_codegen::{CodeGenerator, GeneratorConfig};

fn button() -> CanvasComponent {
    CanvasComponent::Button(ButtonComponent::new("Click me".to_string()))
}

#[test]
fn every_target_produces_output_and_declares_an_extension() {
    let components = [button()];
    let cases: Vec<(&str, Box<dyn CodeGenerator>, &str)> = vec![
        (
            "leptos",
            Box::new(LeptosGenerator::new(Default::default())),
            "rs",
        ),
        ("html", Box::new(HtmlGenerator), "html"),
        ("json", Box::new(JsonGenerator), "json"),
        ("markdown", Box::new(MarkdownGenerator), "md"),
        ("json_schema", Box::new(JsonSchemaGenerator), "schema.json"),
        ("typescript", Box::new(TypeScriptGenerator), "d.ts"),
        ("react", Box::new(ReactGenerator), "tsx"),
        ("vue", Box::new(VueGenerator), "vue"),
        ("css", Box::new(CssGenerator), "css"),
        ("tailwind", Box::new(TailwindHtmlGenerator), "html"),
        ("svelte", Box::new(SvelteGenerator), "svelte"),
    ];

    for (name, generator, extension) in cases {
        assert_eq!(generator.file_extension(), extension, "{name} extension");
        let output = generator.generate(&components, &[]).unwrap();
        assert!(!output.trim().is_empty(), "{name} produced no output");
    }
}

#[test]
fn output_names_no_product_unless_asked() {
    let components = [button()];
    for generator in [
        &CssGenerator as &dyn CodeGenerator,
        &VueGenerator,
        &SvelteGenerator,
    ] {
        let output = generator.generate(&components, &[]).unwrap();
        assert!(
            !output.contains("Leptos Studio"),
            "the default output must not advertise a product, got:\n{output}"
        );
    }
}

#[test]
fn attribution_is_opt_in_and_lands_in_the_output() {
    let components = [button()];
    let config = GeneratorConfig::with_attribution("Generated by Example");

    // Every target that can carry a comment must write the attribution into its
    // output. JsonGenerator is absent on purpose: JSON has no comment syntax, so
    // it documents that it ignores the config rather than corrupting the payload.
    let generators: Vec<(&str, Box<dyn CodeGenerator>)> = vec![
        ("leptos", Box::new(LeptosGenerator::new(Default::default()))),
        ("html", Box::new(HtmlGenerator)),
        ("markdown", Box::new(MarkdownGenerator)),
        ("json_schema", Box::new(JsonSchemaGenerator)),
        ("typescript", Box::new(TypeScriptGenerator)),
        ("react", Box::new(ReactGenerator)),
        ("vue", Box::new(VueGenerator)),
        ("css", Box::new(CssGenerator)),
        ("tailwind", Box::new(TailwindHtmlGenerator)),
        ("svelte", Box::new(SvelteGenerator)),
    ];

    for (name, generator) in generators {
        let output = generator.generate_with(&config, &components, &[]).unwrap();
        assert!(
            output.contains("Generated by Example"),
            "the configured attribution must appear in the {name} output, got:\n{output}"
        );
    }
}

#[test]
fn json_schema_keeps_the_attribution_valid() {
    let components = [button()];
    let config = GeneratorConfig::with_attribution("Generated by Example");
    let output = JsonSchemaGenerator
        .generate_with(&config, &components, &[])
        .unwrap();

    // The note goes in `$comment`, the keyword draft-07 reserves for this, so the
    // document stays parseable and still passes validation.
    let parsed: serde_json::Value =
        serde_json::from_str(&output).expect("output must be valid JSON");
    assert_eq!(
        parsed.get("$comment").and_then(|v| v.as_str()),
        Some("Generated by Example")
    );
    assert!(
        parsed.get("$schema").is_some(),
        "the $comment must not displace the rest of the schema"
    );
}

#[test]
fn json_payload_is_never_polluted_by_an_attribution() {
    let components = [button()];
    let config = GeneratorConfig::with_attribution("Generated by Example");
    let output = JsonGenerator
        .generate_with(&config, &components, &[])
        .unwrap();

    // The payload is the caller's own data, so the generator must not invent a
    // field for the note. It ignores the attribution instead of corrupting output.
    let parsed: serde_json::Value =
        serde_json::from_str(&output).expect("output must be valid JSON");
    assert_eq!(parsed, serde_json::to_value(&components).unwrap());
    assert!(
        !output.contains("Generated by Example"),
        "the JSON payload must not gain an attribution field, got:\n{output}"
    );
}

#[test]
fn default_output_names_no_product_for_every_target() {
    let components = [button()];
    let generators: Vec<(&str, Box<dyn CodeGenerator>)> = vec![
        ("leptos", Box::new(LeptosGenerator::new(Default::default()))),
        ("html", Box::new(HtmlGenerator)),
        ("markdown", Box::new(MarkdownGenerator)),
        ("json_schema", Box::new(JsonSchemaGenerator)),
        ("typescript", Box::new(TypeScriptGenerator)),
        ("react", Box::new(ReactGenerator)),
        ("vue", Box::new(VueGenerator)),
        ("css", Box::new(CssGenerator)),
        ("tailwind", Box::new(TailwindHtmlGenerator)),
        ("svelte", Box::new(SvelteGenerator)),
    ];

    for (name, generator) in generators {
        let output = generator.generate(&components, &[]).unwrap();
        assert!(
            !output.contains("Generated by"),
            "the default {name} output must carry no attribution, got:\n{output}"
        );
    }
}

#[test]
fn legacy_generator_names_still_resolve() {
    // The extraction renamed the generators; the old names are aliases so existing
    // call sites keep compiling.
    fn assert_is_generator<T: CodeGenerator>(_: &T) {}

    let leptos: LeptosCodeGenerator = LeptosCodeGenerator::new(Default::default());
    assert_is_generator(&leptos);
    assert_is_generator(&HtmlCodeGenerator);
    assert_is_generator(&JsonCodeGenerator);
    assert_is_generator(&MarkdownCodeGenerator);
}
