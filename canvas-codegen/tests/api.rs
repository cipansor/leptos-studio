//! The crate's public contract: every target is reachable through one trait, and
//! nothing names a product unless the caller asks for it.

use canvas_codegen::domain::{ButtonComponent, CanvasComponent};
use canvas_codegen::generators::{
    CssGenerator, HtmlCodeGenerator, HtmlGenerator, JsonCodeGenerator, JsonGenerator,
    JsonSchemaGenerator, LeptosCodeGenerator, LeptosGenerator, MarkdownCodeGenerator,
    MarkdownGenerator, ReactGenerator, SvelteGenerator, TailwindHtmlGenerator, TypeScriptGenerator,
    VueGenerator,
};
use canvas_codegen::{CodeGenerator, GeneratorConfig};

fn button() -> CanvasComponent {
    CanvasComponent::Button(ButtonComponent::new("Click me".to_string()))
}

#[test]
fn every_target_produces_output_and_declares_an_extension() {
    let components = [button()];
    let cases: Vec<(&str, Box<dyn CodeGenerator>, &str)> = vec![
        (
            "leptos",
            Box::new(LeptosGenerator::new(Default::default())),
            "rs",
        ),
        ("html", Box::new(HtmlGenerator), "html"),
        ("json", Box::new(JsonGenerator), "json"),
        ("markdown", Box::new(MarkdownGenerator), "md"),
        ("json_schema", Box::new(JsonSchemaGenerator), "schema.json"),
        ("typescript", Box::new(TypeScriptGenerator), "d.ts"),
        ("react", Box::new(ReactGenerator), "tsx"),
        ("vue", Box::new(VueGenerator), "vue"),
        ("css", Box::new(CssGenerator), "css"),
        ("tailwind", Box::new(TailwindHtmlGenerator), "html"),
        ("svelte", Box::new(SvelteGenerator), "svelte"),
    ];

    for (name, generator, extension) in cases {
        assert_eq!(generator.file_extension(), extension, "{name} extension");
        let output = generator.generate(&components, &[]).unwrap();
        assert!(!output.trim().is_empty(), "{name} produced no output");
    }
}

